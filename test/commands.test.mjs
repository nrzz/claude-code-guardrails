test("nested shells are read up to five levels deep, and not beyond", () => {
  // bash -c '...' wrapped n times, each level quoting the one inside it
  const wrap = (cmd, n) => { let s = cmd; for (let i = 0; i < n; i++) s = `bash -c '${s.replace(/'/g, "'\\''")}'`; return s; };
  for (let n = 1; n <= 5; n++) assert.equal(bash(LINUX, wrap("rm -rf /", n)).rule, "rm-root", `${n} levels`);
  assert.equal(bash(LINUX, wrap("rm -rf /", 6)).decision, "allow", "six levels are beyond what is read (documented)");
});

