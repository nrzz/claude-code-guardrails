// A table of commands and what each preset does with them. Every row is a test.
// Decisions are written in the order strict, balanced, relaxed: A = allow, K = ask, D = deny.
import test from "node:test";
import assert from "node:assert/strict";
import { LINUX, MAC, WIN, WORD, bash, fakeGit, pwsh } from "./helpers.mjs";

const PRESETS = ["strict", "balanced", "relaxed"];

function table(title, env, run, rows) {
  for (const [command, d, rule] of rows) {
    test(`${title}: ${command.replace(/\n/g, "\\n")}`, () => {
      PRESETS.forEach((preset, i) => {
        const r = run(env, command, preset);
        assert.equal(r.decision, WORD[d[i]], `${preset}: ${r.reason || "was allowed"}`);
        if (d[i] !== "A" && rule) assert.equal(r.rule, rule, `${preset}: rule`);
      });
    });
  }
}

